AUDIENCE_HINT = {
    "일반": "대상 독자: 일반 성인. 평이한 표현을 쓰되 전문용어는 짧게 풀이.",
    "사회초년생": "대상 독자: 보험 가입 경험이 거의 없는 20대. 용어를 최대한 쉽게, 예시 위주로.",
    "고령자": "대상 독자: 디지털·금융 정보 접근성이 낮은 고령자. 짧은 문장, 큰 개념부터. 겁주지 말고 무엇을 확인하면 되는지 안내.",
}


FOLLOWUP_SYSTEM = (
    "당신은 보험 소비자가 상담 창구에서 물어볼 만한 실질적인 확인 질문을 만듭니다. "
    "주어진 약관 조항과 지적 내용, 그리고 이미 나온 질문을 보고, 그와 겹치지 않는 "
    "새로운 질문만 3개 만드세요. 짧고 구체적으로, 답을 들으면 판단에 도움이 되는 질문으로."
)


DETAIL_SYSTEM = (
    "당신은 금융소비자에게 보험 약관 조항을 깊이 있게 설명하는 전문가입니다. "
    "주어진 약관 조항, 지적 내용, 관련 법조문 요지를 바탕으로 4~6문장의 상세 해설을 씁니다. "
    "구성: (1) 이 조항이 실제로 어떤 상황에서 소비자에게 불리하게 작용하는지 "
    "(2) 관련 법·표준약관은 이 문제를 어떻게 다루는지 (제공된 조문 요지를 인용) "
    "(3) 소비자가 지금 할 수 있는 대응. "
    "제공된 법조문 요지 범위를 벗어나 조문 번호를 지어내지 마세요. 과장 없이."
)


def build_detail_prompt(
    clause_ref: str, quote: str, summary: str, law_texts: list[str], audience: str
) -> str:
    hint = AUDIENCE_HINT.get(audience, AUDIENCE_HINT["일반"])
    laws = "\n".join(f"- {t}" for t in law_texts) or "(관련 조문 요지 없음)"
    return (
        f"{hint}\n\n"
        f"[조항] {clause_ref}\n[약관 원문] {quote}\n[지적] {summary}\n\n"
        f"[관련 법조문 요지]\n{laws}\n\n"
        f"위 내용으로 상세 해설을 작성하세요."
    )


def build_followup_prompt(
    clause_ref: str, quote: str, summary: str, existing: list[str], audience: str
) -> str:
    hint = AUDIENCE_HINT.get(audience, AUDIENCE_HINT["일반"])
    ex = "\n".join(f"- {q}" for q in existing) or "(없음)"
    return (
        f"{hint}\n\n"
        f"[조항] {clause_ref}\n[약관 원문] {quote}\n[지적] {summary}\n"
        f"[이미 나온 질문]\n{ex}\n\n"
        f"위와 겹치지 않는 새 확인 질문 3개."
    )


def build_user_prompt(window_text: str, audience: str) -> str:
    return (
        f"{AUDIENCE_HINT.get(audience, AUDIENCE_HINT['일반'])}\n\n"
        f"다음은 약관 텍스트의 한 구간입니다. 이 구간에서 체크리스트에 걸리는 조항을 찾아 "
        f"Finding 목록으로 만드세요.\n\n"
        f"---- 약관 구간 시작 ----\n{window_text}\n---- 약관 구간 끝 ----"
    )
